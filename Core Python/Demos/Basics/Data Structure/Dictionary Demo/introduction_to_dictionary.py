# 1. Structure :
# {}, key and value pair.

di = {'Name' : 'Shyam', 'Add' : 'Pune', 'Age' : 22}

# 2. Type of data.
# Heterogeneous.

# 3. Sequence :
# Ordered.

# 4. Changeble :
# Key : Immutable , Value : Mutable, Size-Mutable.

di['Course'] = 'Data Science' # Key Doesn't Exist = Adds as a element.
di['Name'] = 'Neymar'         # Key Exist : Value Update

# 5: Duplicates :
# Key : Unique , Value : Duplicates allowed.

print(di)